use std::{fs, path::PathBuf};

use brickui_lib::{api::users::User, bricks::brick::Brick, config::settings::Settings};
use ts_rs::{Config, TS};

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let manifest_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let output_dir = manifest_dir.join("../src/interfaces/generated");

    // Pulizia e creazione della directory di output
    if fs::exists(&output_dir)? {
        fs::remove_dir_all(&output_dir)?;
    }
    fs::create_dir_all(&output_dir)?;

    let config = Config::default().with_out_dir(&output_dir);

    // Esportazione dei tipi Rust
    Brick::export_all(&config)?;
    Settings::export_all(&config)?;
    User::export_all(&config)?;

    // Generazione automatica di index.ts
    let mut index_content = String::new();
    index_content.push_str("// Code generated by bin/typegen. DO NOT EDIT.\n\n");

    let mut export_count = 0;
    for entry in fs::read_dir(&output_dir)? {
        let entry = entry?;
        let path = entry.path();

        if path.is_file() && path.extension().and_then(|s| s.to_str()) == Some("ts") {
            if let Some(file_stem) = path.file_stem().and_then(|s| s.to_str()) {
                // Esclude un eventuale index.ts presistente
                if file_stem != "index" {
                    index_content.push_str(&format!("export * from './{}';\n", file_stem));
                    export_count += 1;
                }
            }
        }
    }

    let index_path = output_dir.join("index.ts");
    fs::write(&index_path, index_content)?;

    println!(
        "Successfully generated TypeScript bindings and index.ts ({export_count} exports) in {:?}",
        output_dir
    );

    Ok(())
}